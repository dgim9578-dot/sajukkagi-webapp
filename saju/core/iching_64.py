def get_hexagram(index: int) -> Hexagram64:
    """0~63 범위의 괘. 범위 밖은 순환."""
    i = int(index) % 64
    return HEXAGRAMS_64[i]


def all_hexagram_labels() -> list[str]:
    """선택 박스용 라벨."""
    return [h.label() for h in HEXAGRAMS_64]
