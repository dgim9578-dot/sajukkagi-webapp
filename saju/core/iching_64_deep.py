def format_deep_gist(short_fallback: str, names_hanja: str) -> str:
    """4문단 해설이 있으면 병합 문자열을, 없으면 기존 한 줄 요지를 그대로 반환합니다."""
    t = ICHING_DEEP_BY_HANJA.get(names_hanja)
    if not t:
        return short_fallback
    a, b, c, d = t
    return f"**{a}** · *핵심*: {b} · *형상*: {c}\n\n{d}"
