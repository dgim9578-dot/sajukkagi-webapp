def _compose(stem: str, branch: str, idx: int, kind: str) -> str:
    if kind == "personality":
        base = STEM_P[stem] + " " + BRANCH_P[branch]
    elif kind == "career":
        base = STEM_C[stem] + " " + BRANCH_C[branch]
    else:
        base = STEM_R[stem] + " " + BRANCH_R[branch]
    note = CYCLE_NOTE[idx % len(CYCLE_NOTE)]
    text = f"{base} {note}"
    if len(text) < 200:
        text += (
            f" {stem}{branch} 일주는 60갑자 중 {idx + 1}번째 조합으로, "
            "개인의 선택·습관·시기와 함께 읽어야 합니다."
        )
    return text.strip()


def build_ilju_db() -> dict[str, dict[str, Any]]:
    entries: dict[str, dict[str, Any]] = {}
    for i in range(60):
        ilju = GAN[i % 10] + ZHI[i % 12]
        entries[ilju] = {
            "hanja": ilju,
            "index": i + 1,
            "personality": _compose(ilju[0], ilju[1], i, "personality"),
            "career": _compose(ilju[0], ilju[1], i, "career"),
            "relationship": _compose(ilju[0], ilju[1], i, "relationship"),
        }
    return entries


def write_ilju_json(path: Path | None = None) -> Path:
    target = path or ILJU_JSON_PATH
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(
        json.dumps(build_ilju_db(), ensure_ascii=False, indent=2),
        encoding="utf-8",
    )
    return target

